import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdtemp, realpath, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { test } from 'node:test';
import { SessionId } from '@deepseek-ai/dsh-session';
import type { CommandRuntime } from '@deepseek-ai/dsh-commands';
import { registerCloudImportCommands } from '../src/import/commands.js';
import { CLOUD_JSON_MAX_BYTES } from '../src/protocol.js';
import { AcceptanceCloud } from './acceptance-helpers.js';
import { coordinatorFixture } from './import-coordinator-fixture.js';

test('actual Native command runtime uses the same import coordinator without model dispatch or recording raw/secret arguments', { timeout: 30_000 }, async t => {
  const root = await realpath(await mkdtemp(join(tmpdir(), 'import-native-command-')));
  let close: (() => Promise<void>) | undefined;
  t.after(async () => { await close?.(); assert.equal(dirname(root), await realpath(tmpdir())); assert.equal(await realpath(root), root); await rm(root, { recursive: true, force: false }); });
  const cloud = new AcceptanceCloud(), host = await coordinatorFixture(join(root, 'host'), cloud); close = () => host.close();
  const stop = registerCloudImportCommands(host.ctx, host.coordinator);
  const actor = await host.ctx.agents.create({ sessionId: SessionId(`actor-${randomUUID()}`), meta: { cwd: host.cwd } });
  const commands = host.ctx.get('commands') as CommandRuntime;
  const signal = new AbortController().signal;
  const before = host.runtimeCalls;
  const inspected = await commands.execute(actor.agent, '/cloud-import {"action":"import-capabilities"}', [], signal);
  assert.equal(inspected?.result.kind, 'success'); assert.equal(host.runtimeCalls, before);
  const rejected = await commands.execute(actor.agent, '/cloud-import {"action":"import-capabilities","connectionString":"CANARY_DO_NOT_RECORD"}', [], signal);
  assert.equal(rejected?.result.kind, 'error');
  const oversized = await commands.execute(actor.agent, `/cloud-import ${'x'.repeat(CLOUD_JSON_MAX_BYTES + 1)}`, [], signal);
  assert.equal(oversized?.result.kind, 'error');
  await host.ctx.sessions.flush(actor.agent.session);
  const events = actor.agent.session.snapshotEvents();
  assert.equal(events.filter(event => event.type === 'command/run').length, 3);
  assert.equal(events.filter(event => event.type === 'command/done').length, 3);
  assert.equal(events.filter(event => event.type === 'user/message').length, 0);
  assert.doesNotMatch(JSON.stringify(events), /CANARY_DO_NOT_RECORD|connectionString|import-capabilities/u);
  assert.equal(host.llmCalls, 0); assert.equal(cloud.activeLeases.size, 0); assert.deepEqual([...host.local.listSessions()], []);
  const stored = await host.source.read(actor.agent.session.id); assert.ok(stored);
  assert.doesNotMatch(JSON.stringify(stored.events), /CANARY_DO_NOT_RECORD|connectionString/u);
  stop(); await actor.dispose();
});
